-- Provision LUP AI Snowflake database, warehouse, resource monitor, and least-privilege roles.
-- Execute with ACCOUNTADMIN / SECURITYADMIN / SYSADMIN during initial Phase 0 setup.

USE ROLE ACCOUNTADMIN;

CREATE RESOURCE MONITOR IF NOT EXISTS LUP_MONTHLY_RM
    WITH CREDIT_QUOTA = 10
    FREQUENCY = MONTHLY
    START_TIMESTAMP = IMMEDIATELY
    TRIGGERS
        ON 75 PERCENT DO NOTIFY
        ON 100 PERCENT DO SUSPEND;

USE ROLE SYSADMIN;

CREATE WAREHOUSE IF NOT EXISTS LUP_WH_XS
    WITH WAREHOUSE_SIZE = 'XSMALL'
    AUTO_SUSPEND = 60
    AUTO_RESUME = TRUE
    INITIALLY_SUSPENDED = TRUE
    RESOURCE_MONITOR = LUP_MONTHLY_RM
    COMMENT = 'LUP AI XSMALL analytics warehouse with 60s auto-suspend';

CREATE DATABASE IF NOT EXISTS LUP_AI_DB
    DATA_RETENTION_TIME_IN_DAYS = 1
    COMMENT = 'LUP AI personal decision intelligence data warehouse';

CREATE SCHEMA IF NOT EXISTS LUP_AI_DB.RAW
    COMMENT = 'Immutable landing tables and stages for daily personal domains';

CREATE SCHEMA IF NOT EXISTS LUP_AI_DB.CORE
    COMMENT = 'Cleaned and normalized tables across finance, habits/sleep, and time/calendar';

CREATE SCHEMA IF NOT EXISTS LUP_AI_DB.ANALYTICS
    COMMENT = 'Cross-domain snapshots, trends, anomalies, goals, and decision logs';

CREATE SCHEMA IF NOT EXISTS LUP_AI_DB.SEMANTIC
    COMMENT = 'Curated read-only views exposed to the LUP AI agent role';

USE ROLE SECURITYADMIN;

CREATE ROLE IF NOT EXISTS LUP_INGEST_RW
    COMMENT = 'ETL and ingestion service role for RAW, CORE, and ANALYTICS';

CREATE ROLE IF NOT EXISTS LUP_AGENT_RO
    COMMENT = 'Least-privilege read-only role for LUP AI runtime on SEMANTIC views';

-- Grant warehouse usage to both roles.
GRANT USAGE ON WAREHOUSE LUP_WH_XS TO ROLE LUP_INGEST_RW;
GRANT USAGE ON WAREHOUSE LUP_WH_XS TO ROLE LUP_AGENT_RO;

-- Ingestion role permissions.
GRANT USAGE ON DATABASE LUP_AI_DB TO ROLE LUP_INGEST_RW;
GRANT ALL PRIVILEGES ON SCHEMA LUP_AI_DB.RAW TO ROLE LUP_INGEST_RW;
GRANT ALL PRIVILEGES ON SCHEMA LUP_AI_DB.CORE TO ROLE LUP_INGEST_RW;
GRANT ALL PRIVILEGES ON SCHEMA LUP_AI_DB.ANALYTICS TO ROLE LUP_INGEST_RW;
GRANT ALL PRIVILEGES ON SCHEMA LUP_AI_DB.SEMANTIC TO ROLE LUP_INGEST_RW;
GRANT ALL PRIVILEGES ON FUTURE TABLES IN SCHEMA LUP_AI_DB.RAW TO ROLE LUP_INGEST_RW;
GRANT ALL PRIVILEGES ON FUTURE TABLES IN SCHEMA LUP_AI_DB.CORE TO ROLE LUP_INGEST_RW;
GRANT ALL PRIVILEGES ON FUTURE TABLES IN SCHEMA LUP_AI_DB.ANALYTICS TO ROLE LUP_INGEST_RW;
GRANT ALL PRIVILEGES ON FUTURE DYNAMIC TABLES IN SCHEMA LUP_AI_DB.ANALYTICS TO ROLE LUP_INGEST_RW;
GRANT ALL PRIVILEGES ON FUTURE VIEWS IN SCHEMA LUP_AI_DB.SEMANTIC TO ROLE LUP_INGEST_RW;

-- Agent role permissions: strictly read-only on SEMANTIC schema.
GRANT USAGE ON DATABASE LUP_AI_DB TO ROLE LUP_AGENT_RO;
GRANT USAGE ON SCHEMA LUP_AI_DB.SEMANTIC TO ROLE LUP_AGENT_RO;
GRANT SELECT ON ALL VIEWS IN SCHEMA LUP_AI_DB.SEMANTIC TO ROLE LUP_AGENT_RO;
GRANT SELECT ON FUTURE VIEWS IN SCHEMA LUP_AI_DB.SEMANTIC TO ROLE LUP_AGENT_RO;

